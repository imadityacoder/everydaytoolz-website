"use client";

import React, { useState, useEffect } from "react";
import {
  ResponsiveContainer,
  AreaChart,
  Area,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
  Legend,
  PieChart,
  Pie,
  Cell,
} from "recharts";
import { Currency, SipResult } from "./types";
import { formatCompact, formatCurrency, formatPercent } from "./formatters";
import { TrendingUp, PieChart as PieIcon, LineChart as ChartIcon } from "lucide-react";

interface SipChartProps {
  result: SipResult;
  currency: Currency;
}

export function SipChart({ result, currency }: SipChartProps) {
  const [chartType, setChartType] = useState<"area" | "donut">("area");
  const [isMounted, setIsMounted] = useState(false);

  useEffect(() => {
    setIsMounted(true);
  }, []);

  // Data for Area Chart
  const areaData = result.yearlyBreakdown.map((item) => ({
    year: `Yr ${item.year}`,
    rawYear: item.year,
    invested: Math.round(item.totalInvested),
    returns: Math.round(item.totalInterest),
    total: Math.round(item.endingBalance),
  }));

  // Data for Donut Chart
  const donutData = [
    {
      name: "Invested Capital",
      value: Math.round(result.totalInvested),
      color: "#7C4DFF",
    },
    {
      name: "Est. Returns",
      value: Math.round(result.estimatedReturns),
      color: "#10B981",
    },
  ];

  const totalValue = result.totalInvested + result.estimatedReturns;
  const returnsPercent = totalValue > 0 ? (result.estimatedReturns / totalValue) * 100 : 0;
  const investedPercent = totalValue > 0 ? (result.totalInvested / totalValue) * 100 : 0;

  if (!isMounted) {
    return (
      <div className="w-full h-80 rounded-2xl border border-border/40 bg-card/40 flex items-center justify-center text-xs text-muted-foreground animate-pulse">
        Loading chart visualizer...
      </div>
    );
  }

  return (
    <div className="w-full rounded-2xl border border-border/60 bg-card p-5 shadow-sm">
      {/* Chart header & switcher */}
      <div className="flex flex-wrap items-center justify-between gap-3 mb-6">
        <div>
          <div className="flex items-center gap-2">
            <TrendingUp className="w-4 h-4 text-primary" />
            <h4 className="text-sm font-semibold text-foreground">
              {chartType === "area" ? "Compounding Growth Projection" : "Wealth Distribution Split"}
            </h4>
          </div>
          <p className="text-xs text-muted-foreground mt-0.5">
            {chartType === "area"
              ? "Year-over-year cumulative growth of principal vs compound interest"
              : "Proportion of total future corpus generated by pure returns"}
          </p>
        </div>

        {/* View Switcher Pills */}
        <div className="flex items-center bg-muted/60 p-1 rounded-xl border border-border/40 text-xs">
          <button
            type="button"
            onClick={() => setChartType("area")}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg font-medium transition-all ${
              chartType === "area"
                ? "bg-card text-foreground shadow-sm"
                : "text-muted-foreground hover:text-foreground"
            }`}
          >
            <ChartIcon className="w-3.5 h-3.5" />
            Growth (Area)
          </button>
          <button
            type="button"
            onClick={() => setChartType("donut")}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg font-medium transition-all ${
              chartType === "donut"
                ? "bg-card text-foreground shadow-sm"
                : "text-muted-foreground hover:text-foreground"
            }`}
          >
            <PieIcon className="w-3.5 h-3.5" />
            Split (Donut)
          </button>
        </div>
      </div>

      {/* Chart Canvas */}
      <div className="w-full h-[320px]">
        {chartType === "area" ? (
          <ResponsiveContainer width="100%" height="100%">
            <AreaChart data={areaData} margin={{ top: 10, right: 10, left: -10, bottom: 0 }}>
              <defs>
                <linearGradient id="sipInvestedGrad" x1="0" y1="0" x2="0" y2="1">
                  <stop offset="5%" stopColor="#7C4DFF" stopOpacity={0.7} />
                  <stop offset="95%" stopColor="#7C4DFF" stopOpacity={0.05} />
                </linearGradient>
                <linearGradient id="sipReturnsGrad" x1="0" y1="0" x2="0" y2="1">
                  <stop offset="5%" stopColor="#10B981" stopOpacity={0.7} />
                  <stop offset="95%" stopColor="#10B981" stopOpacity={0.05} />
                </linearGradient>
              </defs>
              <CartesianGrid strokeDasharray="3 3" stroke="currentColor" className="text-border/40" />
              <XAxis
                dataKey="year"
                stroke="currentColor"
                className="text-xs text-muted-foreground"
                tickLine={false}
              />
              <YAxis
                stroke="currentColor"
                className="text-xs text-muted-foreground"
                tickLine={false}
                tickFormatter={(val: number) => formatCompact(val, currency)}
              />
              <Tooltip
                content={({ active, payload, label }) => {
                  if (active && payload && payload.length) {
                    const data = payload[0].payload;
                    return (
                      <div className="rounded-xl border border-border/80 bg-popover/95 p-3.5 shadow-xl backdrop-blur-md text-xs space-y-1.5 min-w-[190px]">
                        <p className="font-semibold text-foreground border-b border-border/60 pb-1">
                          {label} (Year {data.rawYear})
                        </p>
                        <div className="flex justify-between items-center text-muted-foreground">
                          <span className="flex items-center gap-1.5">
                            <span className="w-2.5 h-2.5 rounded-full bg-[#7C4DFF]" />
                            Invested:
                          </span>
                          <span className="font-semibold text-foreground">
                            {formatCurrency(data.invested, currency)}
                          </span>
                        </div>
                        <div className="flex justify-between items-center text-muted-foreground">
                          <span className="flex items-center gap-1.5">
                            <span className="w-2.5 h-2.5 rounded-full bg-[#10B981]" />
                            Returns:
                          </span>
                          <span className="font-semibold text-emerald-500">
                            +{formatCurrency(data.returns, currency)}
                          </span>
                        </div>
                        <div className="flex justify-between items-center pt-1 border-t border-border/50 text-foreground font-bold">
                          <span>Portfolio Total:</span>
                          <span className="text-primary">
                            {formatCurrency(data.total, currency)}
                          </span>
                        </div>
                      </div>
                    );
                  }
                  return null;
                }}
              />
              <Legend
                verticalAlign="top"
                align="right"
                iconType="circle"
                wrapperStyle={{ paddingBottom: 12, fontSize: 12 }}
              />
              <Area
                type="monotone"
                dataKey="invested"
                name="Invested Capital"
                stackId="1"
                stroke="#7C4DFF"
                strokeWidth={2}
                fillOpacity={1}
                fill="url(#sipInvestedGrad)"
              />
              <Area
                type="monotone"
                dataKey="returns"
                name="Est. Returns"
                stackId="1"
                stroke="#10B981"
                strokeWidth={2}
                fillOpacity={1}
                fill="url(#sipReturnsGrad)"
              />
            </AreaChart>
          </ResponsiveContainer>
        ) : (
          <div className="w-full h-full flex flex-col md:flex-row items-center justify-center gap-6">
            <div className="w-full md:w-1/2 h-full relative flex items-center justify-center">
              <ResponsiveContainer width="100%" height="100%">
                <PieChart>
                  <Pie
                    data={donutData}
                    cx="50%"
                    cy="50%"
                    innerRadius={70}
                    outerRadius={105}
                    paddingAngle={4}
                    dataKey="value"
                  >
                    {donutData.map((entry, index) => (
                      <Cell key={`cell-${index}`} fill={entry.color} stroke="none" />
                    ))}
                  </Pie>
                  <Tooltip
                    content={({ active, payload }) => {
                      if (active && payload && payload.length) {
                        const data = payload[0];
                        return (
                          <div className="rounded-xl border border-border/80 bg-popover/95 p-2.5 shadow-xl backdrop-blur-md text-xs">
                            <span className="font-medium text-foreground">{data.name}: </span>
                            <span className="font-bold text-primary">
                              {formatCurrency(data.value as number, currency)}
                            </span>
                          </div>
                        );
                      }
                      return null;
                    }}
                  />
                </PieChart>
              </ResponsiveContainer>
              {/* Centered Donut Stat */}
              <div className="absolute inset-0 flex flex-col items-center justify-center pointer-events-none text-center">
                <span className="text-[10px] tracking-wider uppercase text-muted-foreground font-semibold">
                  Multiplier
                </span>
                <span className="text-xl font-extrabold text-foreground tracking-tight">
                  {result.wealthMultiplier.toFixed(2)}x
                </span>
              </div>
            </div>

            {/* Donut Legend & Stats */}
            <div className="w-full md:w-1/2 space-y-3">
              <div className="p-3.5 rounded-xl border border-border/50 bg-muted/20 space-y-1">
                <div className="flex items-center justify-between text-xs">
                  <span className="flex items-center gap-2 font-medium text-foreground">
                    <span className="w-3 h-3 rounded-md bg-[#7C4DFF]" />
                    Invested Capital
                  </span>
                  <span className="font-semibold text-foreground">
                    {formatPercent(investedPercent)}
                  </span>
                </div>
                <p className="text-base font-bold text-foreground pl-5">
                  {formatCurrency(result.totalInvested, currency)}
                </p>
              </div>

              <div className="p-3.5 rounded-xl border border-border/50 bg-emerald-500/5 space-y-1">
                <div className="flex items-center justify-between text-xs">
                  <span className="flex items-center gap-2 font-medium text-emerald-600 dark:text-emerald-400">
                    <span className="w-3 h-3 rounded-md bg-[#10B981]" />
                    Estimated Returns
                  </span>
                  <span className="font-semibold text-emerald-600 dark:text-emerald-400">
                    {formatPercent(returnsPercent)}
                  </span>
                </div>
                <p className="text-base font-bold text-emerald-600 dark:text-emerald-400 pl-5">
                  {formatCurrency(result.estimatedReturns, currency)}
                </p>
              </div>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
